def gen_xlsx(path):
    # 0718：功能描述里允许内联 HTML（如 <span style="color">「0718 修订」…</span> 着色标签），
    # 写 Excel 前剥离标签只留纯文本（md 保留着色，xlsx 保留「0718 修订」文字标记）
    strip_tags = lambda s: re.sub(r"<[^>]+>", "", s)
    if not HAS_OPENPYXL:
        raise SystemExit("✗ 未安装 openpyxl，xlsx 未生成——md 与 xlsx 会失步。请先 pip install openpyxl 后重跑。")
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "功能清单"
    head_fill = PatternFill("solid", fgColor="4B57E8")
    head_font = Font(bold=True, color="FFFFFF", size=11)
    duan_fill = PatternFill("solid", fgColor="EEF0FF")
    thin = Side(style="thin", color="DDDDDD")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    wrap = Alignment(wrap_text=True, vertical="top")
    top = Alignment(vertical="top")

    headers = ["端", "模块", "功能点", "二级功能", "功能描述"]
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = head_fill; cell.font = head_font
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = border
    duan_titles = {
        M: "移动端 H5（C 端用户）", O: "机构后台 PC（机构运营）",
        P: "平台超管后台 PC", G: "三端通用（全局交互）",
    }
    r = 2
    for duan, mod, fp, sub, bullets, change in rows:
        desc = "\n".join(f"（{i}）{strip_tags(bullet_text(b))}" for i, b in enumerate(bullets, 1))
        if change:
            desc = f"{CHANGE_DATE}{change}\n" + desc
        ws.cell(row=r, column=1, value=duan_titles[duan])
        # 0617 定案：xlsx「模块」列去掉序号前缀（md 章节标题保留序号）。
        # 此前只改 xlsx 后处理、没写进生成器，导致每次重跑序号又被加回来，故在此固化。
        ws.cell(row=r, column=2, value=re.sub(r"^\d+\.\s*", "", mod))
        ws.cell(row=r, column=3, value=fp)
        ws.cell(row=r, column=4, value=sub or "—")
        ws.cell(row=r, column=5, value=desc)
        for c in range(1, 6):
            cell = ws.cell(row=r, column=c)
            cell.border = border
            cell.alignment = wrap if c == 5 else top
            if c == 1:
                cell.fill = duan_fill
            if change and c in (3, 4, 5):
                cell.font = Font(color="DC2626")  # 变更行标红，与线上飞书表格一致
        r += 1
    ws.column_dimensions["A"].width = 20
    ws.column_dimensions["B"].width = 22
    ws.column_dimensions["C"].width = 26
    ws.column_dimensions["D"].width = 20
    ws.column_dimensions["E"].width = 95
    ws.freeze_panes = "A2"

    # 附表 sheets
    def add_sheet(title, header, data, widths):
        s = wb.create_sheet(title)
        s.append(header)
        for c in range(1, len(header) + 1):
            cell = s.cell(row=1, column=c)
            cell.fill = head_fill; cell.font = head_font
            cell.alignment = Alignment(horizontal="center", vertical="center"); cell.border = border
        for i, row in enumerate(data, start=2):
            for c, v in enumerate(row, start=1):
                cell = s.cell(row=i, column=c, value=v)
                cell.border = border; cell.alignment = wrap
        for col, w in zip("ABCDEFG", widths):
            s.column_dimensions[col].width = w
        s.freeze_panes = "A2"
    add_sheet("数据看板指标", BOARD_HEADER, BOARD, [22, 40, 38, 30, 22])
    add_sheet("用量看板指标", USAGE_HEADER, USAGE, [28, 22, 52, 38])
    wb.save(path)

