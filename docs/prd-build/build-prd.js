function imgSize(p) { const b = fs.readFileSync(p); return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) }; }
function FIG(file, caption) {
  const p = path.join(FIGDIR, file);
  const d = imgSize(p);
  const maxW = 624;
  const w = Math.min(maxW, d.w), h = Math.round(w * d.h / d.w);
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 140, after: 50 }, children: [new ImageRun({ type: 'png', data: fs.readFileSync(p), transformation: { width: w, height: h }, altText: { title: caption, description: caption, name: caption } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 180 }, children: [new TextRun({ text: caption, italics: true, size: 17, color: CLR.sub, font: CJK })] }),
  ];
}
