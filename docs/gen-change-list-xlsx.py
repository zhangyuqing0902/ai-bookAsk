def sheet(title, header, rows, widths, red_col=None, freeze="A2"):
    ws = wb.create_sheet(title)
    ws.append(header)
    for c in range(1, len(header) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill, cell.font, cell.border = HEAD_FILL, HEAD_FONT, BORDER
        cell.alignment = Alignment(horizontal="center", vertical="center")
    for r_i, row in enumerate(rows, start=2):
        for c_i, val in enumerate(row, start=1):
            cell = ws.cell(row=r_i, column=c_i, value=val)
            cell.border, cell.alignment = BORDER, WRAP
            cell.font = Font(size=10)
        # 整行分节标题（第一列有值、其余为空）
        if len(row) > 1 and row[0] and all(not x for x in row[1:]):
            for c_i in range(1, len(header) + 1):
                ws.cell(row=r_i, column=c_i).fill = SEC_FILL
                ws.cell(row=r_i, column=c_i).font = BOLD
        elif red_col is not None and len(row) > red_col and row[red_col]:
            ws.cell(row=r_i, column=red_col + 1).font = RED
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    ws.freeze_panes = freeze
    return ws


